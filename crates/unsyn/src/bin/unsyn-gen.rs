//! Writes this crate's own front end from `unsyn.us`.
//!
//! `unsyn.us` is the spec of the language — its terminals, its nodes, its
//! separator and the visitor over a file of it — and the crate reads and walks
//! that tree, so the tree is what the generator writes rather than a file
//! somebody keeps by hand. The four files land in `src/generated` and are
//! committed, which is what lets the crate build without a build script: a
//! generator run from the tree needs no earlier release of itself, so there is
//! no build-time edge to follow and no release that lags the code it ships.
//!
//! Running this is a deliberate act, not a step of a build:
//!
//! ```sh
//! cargo run -p unsyn --bin unsyn-gen && cargo fmt
//! ```
//!
//! `cargo fmt` because the generator writes code in one line and leaves the
//! layout to the formatter, and the committed files are read by people.
//! A directory other than `src/generated` may be named as the first argument,
//! which is what lets a test have the code written without touching what is
//! committed.
//!
//! `tests/generated.rs` then fails when what is committed and what the
//! generator writes come apart, so a change to `unsyn.us` or to the generator
//! cannot be committed without its output.
//!
//! One of the five files a build normally writes is absent, and that is
//! deliberate: [`input_at`] says the stream trait stands in `src/input.rs`
//! rather than being written again. The trait is the one thing no grammar can
//! derive — it is bounded by what the *passes over* the tree need (a prefix
//! test, a look-ahead, a snapshot), which no production of the language states,
//! and it carries the tests of the stream itself.
//!
//! The error is not exempt and is written here, as `src/generated/error.rs`,
//! which `src/error.rs` mounts as `error::generated`: what reading a file reports,
//! a combinator's own failure and a refusal named after a rule of the spec. What
//! the analysis adds — a token well formed and meaningless, a shape no code
//! answers — is not derivable from a grammar, so that file wraps the generated
//! error together with those families into the one type every pass returns.
//!
//! [`input_at`]: unsyn::codegen::Builder::input_at

use std::path::PathBuf;
use std::str::FromStr;

use proc_macro2::TokenStream;

/// The spec, read from the crate's own directory.
const SOURCE: &str = include_str!("../../unsyn.us");

/// Where the files go unless an argument says otherwise, which is a directory of
/// the crate rather than a directory a build made: what is committed has to be
/// findable by a reader, a formatter and a diff, and it cannot be named by a
/// `path` attribute otherwise.
const DIR: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/src/generated");

/// What stands above each file: what it holds, and the one fact a reader of it
/// needs before anything else — that it is written, not kept.
const HEADERS: &[(&str, &str)] = &[
    (
        "error.rs",
        "What reading a file of the language reports, named after the rules of `unsyn.us`.",
    ),
    (
        "lexer.rs",
        "The terminals of the language, each reading one token out of the characters it is handed.",
    ),
    (
        "syntax.rs",
        "The nodes of the language, each a shape the production that names it says.",
    ),
    (
        "visit.rs",
        "The visitor over a file of the language, one method per rule.",
    ),
];

/// The one external `unsyn.us` calls, bound to a scan of this crate's own.
///
/// A generated file reaches it by the path written here, which is what an
/// external is: the caller decides what a call means, and here the caller is the
/// crate the code lands in. The scan reads a name whole — the start of one and
/// then the greedy run that continues it — because a token that is "whatever the
/// Unicode property was" is still one token. Nothing else is bound here: what a
/// spec does not call, this run has no reason to answer.
const IDENT_OR_KEYWORD: &str = "crate::scan::scan_ident_or_keyword";

fn main() {
    // A directory may be named on the command line, which is how
    // `tests/generated.rs` asks for the code without letting this run loose on
    // what is committed.
    let dir = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(DIR));

    std::fs::create_dir_all(&dir).expect("the generated directory can be made");

    for module in modules() {
        let path = dir.join(module.file);
        let header = HEADERS
            .iter()
            .find(|(file, _)| *file == module.file)
            .map(|(_, text)| *text)
            .unwrap_or("Code written from `unsyn.us`.");

        std::fs::write(
            &path,
            format!(
                "//! {header}\n//!\n//! Generated by `cargo run -p unsyn --bin unsyn-gen` from \
                 `unsyn.us`.\n//! Do not edit: `tests/generated.rs` refuses a file that differs \
                 from what the generator writes.\n\n{code}\n",
                code = module.code,
            ),
        )
        .expect("a file of the crate can be written");

        println!("wrote {}", path.display());
    }
}

/// The files the spec is written into, each with the code of it.
///
/// This is the same list a build script would be handed by
/// [`to_dir`](unsyn::codegen::Builder::to_dir); taken apart from the filesystem
/// here so that the header above can stand above the code rather than inside it.
fn modules() -> Vec<unsyn::codegen::Module> {
    unsyn::codegen::Builder::from_source(SOURCE)
        .expect("unsyn.us is a file of the language")
        .external("IdentOrKeyword", tokens(IDENT_OR_KEYWORD))
        // The stream trait is this crate's own, reached by path: the bounds the
        // passes below are written against are wider than any grammar states,
        // and the trait is documented and tested by hand.
        .input_at(tokens("crate::input::UnsynInput"))
        // The error is not. It is written here — the framework's kind and the
        // family of rules a refusal is named after, both from the spec — and
        // `src/error.rs` wraps that together with the families of the analysis,
        // which no production states. It is named `ParseError` rather than after
        // the language because the wrapper is the crate's error, and this is the
        // phase of it that reading a file produces.
        .error_name("ParseError")
        .modules()
        .expect("unsyn.us builds")
}

/// The path or expression an external is written as.
fn tokens(path: &str) -> TokenStream {
    TokenStream::from_str(path).expect("a path is a token stream")
}
